#!/usr/bin/env python3
"""Designs the decimation filter of the ESP32-C5 receiver (rx/c5rx).
Stage 1 (hardware): the IQ estimator's running sums read at twice the output rate (1 Msps, 666.7 ksps, 500 ksps), i.e. a boxcar
over one input period of the 80 MHz ADC samples.
Stage 2 (firmware): one halfband FIR, decimate by 2. The ESP32-S3 receiver's band edges (third_party/ESP32-DATV-RX/esp32-sdr-trx/
firmware/tools/design_taps.py: 200/300 kHz at 500 ksps out, 133/200 at 333, 100/150 at 250) are 0.2 / 0.3 of the input rate in
all three cases, so the same taps serve them all. A halfband has every second tap zero; its passband cannot equalise the
boxcar's droop (-0.6 dB at the passband edge).
A shorter one (N_FAST) for 400 ksps out, where the CPU is short.
Writes ../main/fir_taps.h (Q15: the centre tap and the non-zero taps of one half, nearest the centre first) and prints the response.
Needs numpy and scipy.
"""
import os
import numpy as np
from scipy.signal import remez, freqz

N = 27                                  # 4 m + 3: (N + 1) / 2 = 14 non-zero taps besides the centre (-51 dB; the boxcar lets
                                        # its images through at -12.6 dB anyway, and each pair costs ~10 cycles)
N_FAST = 19                             # 400 ksps out (300 cycles per input): -40 dB, two pairs fewer
FP, FST = 0.2, 0.3                      # of the input rate


def box_mag(f):                         # boxcar over one input period (f in units of the input rate)
    return np.abs(np.sinc(f))


def design(N):
    h = remez(N, [0, FP, FST, 0.5], [1, 0], fs=1.0)
    c = (N - 1) // 2
    for k in range(N):                  # exact halfband: even distances from the centre are zero, the centre 1/2
        if (k - c) % 2 == 0:
            h[k] = 0.0
    h[c] = 0.5
    h /= h.sum()
    q = np.round(h * 32768).astype(int)
    return q, c


def report(q):
    N = len(q)
    h = q / 32768.0
    f = np.linspace(0, 0.5, 20001)
    _, H = freqz(h, worN=f, fs=1.0)
    tot = np.abs(H) * box_mag(f)
    pb, sb = tot[f <= FP], tot[f >= FST]
    worst = 0.0
    for k in (1, 2, 3):
        fi = np.linspace(k - FP, k + FP, 4001)
        _, Hi = freqz(h, worN=np.mod(fi, 1.0), fs=1.0)
        worst = max(worst, np.max(np.abs(Hi) * box_mag(fi)))
    print(f"{N} taps halfband: passband (<{FP}) {20 * np.log10(pb.max()):+.2f} / {20 * np.log10(pb.min()):+.2f} dB with the boxcar, "
          f"stopband (>{FST}) {20 * np.log10(sb.max()):.1f} dB, boxcar image alias {20 * np.log10(worst):.1f} dB")


def main():
    out = ["/* Generated by tools/design_taps.py - do not edit. Q15 halfband: y = C x[c] + sum_j S[j] (x[c - 2j - 1] + x[c + 2j + 1]). */",
           "#pragma once", "#include <stdint.h>", ""]
    for n, pre, name in ((N, "FIR", "fir_side"), (N_FAST, "FIR_FAST", "fir_fast_side")):
        q, c = design(n)
        report(q)
        side = [q[c + d] for d in range(1, c + 1, 2)]
        assert all(q[c + d] == q[c - d] for d in range(c + 1)) and all(q[c + d] == 0 for d in range(2, c + 1, 2))
        out += [f"#define {pre}_TAPS {n}", f"#define {pre}_SIDE {len(side)}", f"#define {pre}_CENTRE {q[c]}",
                f"static const int16_t {name}[{pre}_SIDE] = {{" + ", ".join(map(str, side)) + "};"]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "fir_taps.h")
    open(path, "w").write("\n".join(out) + "\n")
    print("->", os.path.normpath(path))


if __name__ == "__main__":
    main()
