#!/usr/bin/env python3
"""Generates ldpc_tables.h (DVB-S2 LDPC parity bit address tables, EN 302 307-1 Annex B and C) for the encoder from
dvb_s2_tables.hh of Ahmet Inan's LDPC code (0BSD; android/native/build-native.sh fetches it at a fixed commit).

    python3 android/native/dvbs2enc/gen_ldpc_tables.py [path/to/dvb_s2_tables.hh]

Each table is a list of rows, one per group of 360 information bits; a row lists the parity bit addresses for the
group's first bit. DEG[] / LEN[] give the row lengths: LEN[i] rows of DEG[i] addresses each.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
CANDIDATES = [os.path.join(HERE, "..", "build", "src", "LDPC", "dvb_s2_tables.hh"),
              os.path.join(ROOT, "third_party", "ESP32-DATV-RX", "build", "LDPC", "dvb_s2_tables.hh")]
# table name -> (code rate, short frame)
NAMES = {"B1": "1/4", "B2": "1/3", "B3": "2/5", "B4": "1/2", "B5": "3/5", "B6": "2/3", "B7": "3/4", "B8": "4/5",
         "B9": "5/6", "B10": "8/9", "B11": "9/10", "C1": "1/4", "C2": "1/3", "C3": "2/5", "C4": "1/2", "C5": "3/5",
         "C6": "2/3", "C7": "3/4", "C8": "4/5", "C9": "5/6", "C10": "8/9"}


def ints(body, name):
    m = re.search(name + r"\[\]\s*=\s*\{([^}]*)\}", body)
    return [int(v) for v in re.findall(r"\d+", m.group(1))]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else next((p for p in CANDIDATES if os.path.exists(p)), None)
    if not src:
        sys.exit("dvb_s2_tables.hh not found: run android/native/build-native.sh, or give its path")
    text = open(src).read()
    out = ["/* Generated by gen_ldpc_tables.py from dvb_s2_tables.hh - do not edit by hand.",
           " * DVB-S2 LDPC parity bit address tables (EN 302 307-1 Annex B: normal frames, Annex C: short frames).",
           " * Source: https://github.com/Blockstream/LDPC (Copyright 2018 Ahmet Inan <xdsopl@gmail.com>, 0BSD:",
           " * permission to use, copy, modify and/or distribute for any purpose with or without fee is granted). */",
           "#pragma once", "#include <stdint.h>", "",
           "typedef struct {",
           "    const char *rate;        /* code rate, e.g. \"3/4\" */",
           "    int short_frame;         /* 0: N = 64800, 1: N = 16200 */",
           "    int n, k;                /* LDPC codeword and information bits */",
           "    int ngroups;             /* row groups: len[i] rows of deg[i] addresses */",
           "    const uint8_t *deg, *len;",
           "    const uint16_t *pos;     /* all rows, one after the other */",
           "} ldpc_table;", ""]
    descs = []
    for m in re.finditer(r"struct DVB_S2_TABLE_(\w+)\s*\{(.*?)\n\};", text, re.S):
        name, body = m.group(1), m.group(2)
        n = int(re.search(r"\bN\s*=\s*(\d+)", body).group(1))
        k = int(re.search(r"\bK\s*=\s*(\d+)", body).group(1))
        deg, ln, pos = ints(body, "DEG"), ints(body, "LEN"), ints(body, "POS")
        deg, ln = [d for d in deg if d], [x for x in ln if x]          # the lists end with 0
        assert len(deg) == len(ln) and sum(ln) * 360 == k, name
        assert sum(d * x for d, x in zip(deg, ln)) == len(pos), name
        assert max(pos) < n - k, name
        low = name.lower()
        out.append(f"static const uint8_t ldpc_{low}_deg[] = {{ {', '.join(map(str, deg))} }};")
        out.append(f"static const uint8_t ldpc_{low}_len[] = {{ {', '.join(map(str, ln))} }};")
        out.append(f"static const uint16_t ldpc_{low}_pos[] = {{")
        for i in range(0, len(pos), 16):
            out.append("    " + ", ".join(map(str, pos[i:i + 16])) + ",")
        out.append("};")
        descs.append(f'    {{ "{NAMES[name]}", {int(name[0] == "C")}, {n}, {k}, {len(deg)}, ldpc_{low}_deg, ldpc_{low}_len, ldpc_{low}_pos }},')
    assert len(descs) == len(NAMES), f"found {len(descs)} tables"
    out += ["", "static const ldpc_table ldpc_tables[] = {"] + descs + ["};",
            "#define LDPC_TABLES (sizeof ldpc_tables / sizeof ldpc_tables[0])", ""]
    dst = os.path.join(HERE, "ldpc_tables.h")
    open(dst, "w").write("\n".join(out))
    print(f"{len(descs)} tables from {src} -> {dst}")


if __name__ == "__main__":
    main()
